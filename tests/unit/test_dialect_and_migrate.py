from pathlib import Path

import pytest

from nwb.db.database import SqliteDatabase, _split_sql
from nwb.db.dialect import to_dialect_ddl, to_dialect_params
from nwb.db.migrate import Migrator, split_role_ddl
from nwb.errors import MigrationError
from nwb.ports import Dialect, SqlDatabase

_DROPPED = ("memories", "memory_versions", "memory_embeddings", "session_notes")


def test_named_params_translate_for_postgres_only():
    sql = "SELECT * FROM t WHERE a = :a AND b::date = :b_2"
    assert to_dialect_params(sql, Dialect.SQLITE) == sql
    assert to_dialect_params(sql, Dialect.POSTGRES) == "SELECT * FROM t WHERE a = %(a)s AND b::date = %(b_2)s"


def test_percent_is_escaped_for_psycopg():
    assert to_dialect_params("SELECT 'x%' WHERE a = :a", Dialect.POSTGRES) == "SELECT 'x%%' WHERE a = %(a)s"


def test_integer_pk_becomes_identity_on_postgres():
    ddl = "CREATE TABLE x (id INTEGER PRIMARY KEY, v TEXT);"
    assert "GENERATED BY DEFAULT AS IDENTITY" in to_dialect_ddl(ddl, Dialect.POSTGRES)
    assert to_dialect_ddl(ddl, Dialect.SQLITE) == ddl


def test_split_sql_ignores_comments_and_blank_statements():
    script = "CREATE TABLE a (x INT); -- trailing\n-- only comment;\nINSERT INTO a VALUES (1),\n (2);\n"
    assert _split_sql(script) == ["CREATE TABLE a (x INT);", "INSERT INTO a VALUES (1),\n (2);"]


def test_migrator_is_idempotent_and_filters_dialect(tmp_path: Path):
    (tmp_path / "0001_a.sql").write_text("CREATE TABLE a (id INTEGER PRIMARY KEY);")
    (tmp_path / "0002_pg_only.pg.sql").write_text("THIS IS NOT SQLITE;")
    db = SqliteDatabase(tmp_path / "m.sqlite")
    m = Migrator(db, tmp_path)
    assert m.migrate() == ["0001_a.sql"]
    assert m.migrate() == []


def test_role_ddl_is_split_out_of_the_transaction_script():
    script = (Path(__file__).resolve().parents[2] / "migrations" / "0004_rls.pg.sql").read_text()
    roles, body = split_role_ddl(script)
    assert len(roles) == 1
    assert "CREATE ROLE nw_app" in roles[0]
    assert "CREATE ROLE" not in body
    assert "GRANT USAGE ON SCHEMA public TO nw_app" in body


def test_sql_memory_tables_are_dropped(db: SqlDatabase) -> None:
    """0018 removes the unused memory tables on both dialects. sessions.notes_status stays."""
    params = {"a": _DROPPED[0], "b": _DROPPED[1], "c": _DROPPED[2], "d": _DROPPED[3]}
    if db.dialect is Dialect.SQLITE:
        tables = "SELECT name FROM sqlite_master WHERE type = 'table' AND name IN (:a, :b, :c, :d)"
        column = "SELECT name FROM pragma_table_info('sessions') WHERE name = 'notes_status'"
    else:
        tables = (
            "SELECT table_name AS name FROM information_schema.tables "
            "WHERE table_schema = 'public' AND table_name IN (:a, :b, :c, :d)"
        )
        column = (
            "SELECT column_name AS name FROM information_schema.columns "
            "WHERE table_schema = 'public' AND table_name = 'sessions' AND column_name = 'notes_status'"
        )
    with db.unit_of_work() as uow:
        assert uow.fetchall(tables, params) == []
        assert uow.fetchone(column) is not None


def test_migrator_rejects_bad_names_and_rolls_back(tmp_path: Path):
    (tmp_path / "bad.sql").write_text("")
    with pytest.raises(MigrationError):
        Migrator(SqliteDatabase(":memory:"), tmp_path).discover()
    (tmp_path / "bad.sql").unlink()
    (tmp_path / "0001_broken.sql").write_text("CREATE TABLE ok (id INT);\nCREATE TABLE broken (;\n")
    db = SqliteDatabase(tmp_path / "r.sqlite")
    with pytest.raises(MigrationError):
        Migrator(db, tmp_path).migrate()
    with db.unit_of_work() as uow:
        assert uow.fetchone("SELECT name FROM sqlite_master WHERE name = 'ok'") is None
