"""Portable SQL helpers. We write SQL with ``:name`` params and translate per dialect."""

from __future__ import annotations

import re

from nwb.ports import Dialect

_NAMED = re.compile(r"(?<![:\w]):([A-Za-z_]\w*)")
_INT_PK = re.compile(r"\bid INTEGER PRIMARY KEY\b")


def to_dialect_params(sql: str, dialect: Dialect) -> str:
    """``:name`` -> ``%(name)s`` for psycopg; unchanged for sqlite. ``::casts`` are left alone."""
    if dialect is Dialect.SQLITE:
        return sql
    return _NAMED.sub(r"%(\1)s", sql.replace("%", "%%"))


def to_dialect_ddl(script: str, dialect: Dialect) -> str:
    """Make portable DDL dialect-correct (auto-increment integer keys on Postgres)."""
    if dialect is Dialect.SQLITE:
        return script
    return _INT_PK.sub("id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY", script)
